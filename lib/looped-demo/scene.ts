// Turns one forward pass of the demo model into the narrated step timeline the
// "Follow your prompt" figure plays through.
import { config, forward, rowOf, topK, type Forward, type Prediction } from "./model";
import { tokenize, type Token } from "./tokenizer";

export type Stage =
  | "tokenize" | "embed" | "attend" | "ff" | "return" | "readout" | "emit";

export type Step = {
  stage: Stage;
  /** 1-based loop this step belongs to; 0 for the stages outside the loop. */
  loop: number;
};

export type Scene = {
  text: string;
  tokens: Token[];
  ids: number[];
  loops: number;
  pass: Forward;
  steps: Step[];
  /** Colour scale shared by every hidden-state strip in the figure. */
  hiddenScale: number;
  /** Colour scale for the embedding strips. */
  embedScale: number;
  predictions: Prediction[];
  /** Index of the step that pauses on the first playthrough. */
  firstReturnStep: number;
  /** How many of the trailing tokens were generated by the model. */
  generated: number;
};

export function buildSteps(loops: number): Step[] {
  const steps: Step[] = [
    { stage: "tokenize", loop: 0 },
    { stage: "embed", loop: 0 },
  ];
  for (let t = 1; t <= loops; t += 1) {
    steps.push({ stage: "attend", loop: t });
    steps.push({ stage: "ff", loop: t });
    if (t < loops) steps.push({ stage: "return", loop: t });
  }
  steps.push({ stage: "readout", loop: loops });
  steps.push({ stage: "emit", loop: loops });
  return steps;
}

function percentile(values: number[], q: number): number {
  if (values.length === 0) return 1;
  const sorted = [...values].sort((a, b) => a - b);
  const v = sorted[Math.min(sorted.length - 1, Math.floor(sorted.length * q))];
  return v > 0 ? v : 1;
}

/**
 * Build a scene. `extraScales` lets a comparison run contribute to the colour
 * scale, so two runs stay directly comparable cell for cell.
 */
export function buildScene(
  text: string, loops: number, generated = 0,
): Scene {
  const tokens = tokenize(text);
  const ids = tokens.map((t) => t.id);
  const pass = forward(ids, loops);
  const steps = buildSteps(loops);

  const hiddenValues: number[] = [];
  for (const lt of pass.loops) {
    for (let i = 0; i < lt.hidden.length; i += 1) hiddenValues.push(Math.abs(lt.hidden[i]));
  }
  const embedValues: number[] = [];
  for (let i = 0; i < pass.embedding.length; i += 1) {
    embedValues.push(Math.abs(pass.embedding[i]));
  }

  return {
    text,
    tokens,
    ids,
    loops,
    pass,
    steps,
    hiddenScale: percentile(hiddenValues, 0.99),
    embedScale: percentile(embedValues, 0.99),
    predictions: topK(pass.logits, Math.max(0, pass.length - 1), 5),
    firstReturnStep: steps.findIndex((s) => s.stage === "return"),
    generated,
  };
}

/** The hidden state of `position` after `loop` loops (loop 0 = all zeros). */
export function hiddenAt(scene: Scene, loop: number, position: number): Float64Array {
  if (loop <= 0) return new Float64Array(config.dModel);
  const lt = scene.pass.loops[Math.min(loop, scene.pass.loops.length) - 1];
  return rowOf(lt.hidden, position);
}

export function embeddingAt(scene: Scene, position: number): Float64Array {
  return rowOf(scene.pass.embedding, position);
}

export type AttentionEdge = { position: number; token: string; weight: number };

/** One query position's attention for one head at one loop, biggest first. */
export function attentionFor(
  scene: Scene, loop: number, head: number, position: number,
): AttentionEdge[] {
  const lt = scene.pass.loops[Math.min(loop, scene.pass.loops.length) - 1];
  if (!lt) return [];
  const row = lt.attention[head]?.[position] ?? [];
  return row
    .map((weight, i) => ({
      position: i,
      token: scene.tokens[i]?.surface ?? "",
      weight,
    }))
    .filter((e) => e.weight > 0)
    .sort((a, b) => b.weight - a.weight);
}

/** Per-head summary used to label the head selector honestly. */
export function headSummaries(
  scene: Scene, loop: number, position: number,
): { head: number; top: AttentionEdge | undefined }[] {
  return Array.from({ length: config.nHeads }, (_, head) => ({
    head,
    top: attentionFor(scene, loop, head, position)[0],
  }));
}

/** How many of the 32 dimensions moved by more than `eps` during `loop`. */
export function changedDims(
  scene: Scene, loop: number, position: number, eps = 0.05,
): { changed: number; maxDelta: number; maxDim: number } {
  const before = hiddenAt(scene, loop - 1, position);
  const after = hiddenAt(scene, loop, position);
  let changed = 0;
  let maxDelta = 0;
  let maxDim = 0;
  for (let i = 0; i < config.dModel; i += 1) {
    const d = Math.abs(after[i] - before[i]);
    if (d > eps) changed += 1;
    if (d > maxDelta) {
      maxDelta = d;
      maxDim = i;
    }
  }
  return { changed, maxDelta, maxDim };
}

export const STAGE_LABEL: Record<Stage, string> = {
  tokenize: "Tokenize",
  embed: "Embed",
  attend: "Attention",
  ff: "Feed-forward",
  return: "Back into the same block",
  readout: "Output head",
  emit: "Generate",
};

function pct(x: number): string {
  const v = x * 100;
  // Never round a near-certain prediction up to a flat 100%.
  if (v >= 99.95) return `${v.toFixed(2)}%`;
  if (v >= 1) return `${v.toFixed(1)}%`;
  return `${v.toFixed(2)}%`;
}

/** The plain-English line under the controls. Every number is from the pass. */
export function narrate(
  scene: Scene, stepIndex: number, head: number, position: number,
): string {
  const step = scene.steps[stepIndex];
  if (!step) return "";
  const tok = scene.tokens[position];
  const word = tok ? `“${tok.surface}”` : "the selected token";
  const last = scene.tokens[scene.tokens.length - 1];

  switch (step.stage) {
    case "tokenize": {
      const oov = scene.tokens.filter((t) => t.oov).length;
      return (
        `The sentence becomes ${scene.tokens.length} tokens. Each one is a row index ` +
        `into a ${config.vocabSize}-entry vocabulary` +
        (oov > 0
          ? `. ${oov} of them fell back to single characters, because the word is not in the vocabulary.`
          : `. Click a token to see its id and the characters it came from.`)
      );
    }
    case "embed":
      return (
        `Every token id picks one row out of the embedding table, and its position adds ` +
        `a second row. The ${config.dModel} numbers under each word are that sum: the ` +
        `vector e. Hold on to it — the loop adds e back in on every single pass.`
      );
    case "attend": {
      const edges = attentionFor(scene, step.loop, head, position);
      const top = edges[0];
      const second = edges[1];
      if (!top) return `Loop ${step.loop}: attention.`;
      // The same word can appear more than once, so always say which one.
      const name = (e: AttentionEdge) =>
        e.position === position
          ? "itself"
          : `“${scene.tokens[e.position]?.surface ?? ""}” (position ${e.position})`;
      return (
        `Loop ${step.loop}, attention. Head ${head + 1} lets ${word} read from the words ` +
        `before it. It puts ${pct(top.weight)} of its attention on ${name(top)}` +
        (second ? ` and ${pct(second.weight)} on ${name(second)}` : "") +
        `. Click any earlier word to read its exact weight.`
      );
    }
    case "ff": {
      const d = changedDims(scene, step.loop, position);
      return (
        `Loop ${step.loop}, feed-forward. Each position now updates its own state from ` +
        `what it just read. For ${word}, ${d.changed} of the ${config.dModel} numbers moved ` +
        `by more than 0.05 this pass; the biggest move was ${d.maxDelta.toFixed(2)} at ` +
        `dimension ${d.maxDim}.`
      );
    }
    case "return": {
      const d = changedDims(scene, step.loop + 1, position);
      return (
        `End of loop ${step.loop}. The state h travels back along the feedback arrow into ` +
        `the same block — the same θ, not a new layer — and e is added to it again. ` +
        `Compare the two strips below: ${d.changed} of ${config.dModel} numbers differ, the rest ` +
        `carried over unchanged. Nothing in the weights moved; only the state did.`
      );
    }
    case "readout": {
      const best = scene.predictions[0];
      const runner = scene.predictions[1];
      return (
        `After ${scene.loops} loop${scene.loops === 1 ? "" : "s"}, the vector at the last ` +
        `position — “${last?.surface ?? ""}” — goes through the final norm and the output head, ` +
        `which scores all ${config.vocabSize} tokens. ` +
        (best
          ? `“${best.token}” wins with ${pct(best.p)}` +
            (runner ? `, ahead of “${runner.token}” at ${pct(runner.p)}.` : ".")
          : "")
      );
    }
    case "emit": {
      const best = scene.predictions[0];
      return (
        `“${best?.token ?? ""}” is appended to the sentence. That is one generated token, ` +
        `after ${scene.loops} internal loop${scene.loops === 1 ? "" : "s"} — the two counters ` +
        `are separate. Press “Generate one more token” to run the whole loop again on the ` +
        `longer sentence.`
      );
    }
    default:
      return "";
  }
}

export type StripView = {
  /** Flat length × dModel values. */
  values: Float64Array;
  scale: number;
  /** Short maths label for what is on screen, e.g. "h² + e". */
  label: string;
  /** Longer description for the legend. */
  description: string;
};

const SUP = ["⁰", "¹", "²", "³", "⁴", "⁵", "⁶", "⁷", "⁸"];

/** Which vectors the token strips show at `stepIndex`. */
export function stripView(scene: Scene, stepIndex: number): StripView | null {
  const step = scene.steps[stepIndex];
  if (!step || step.stage === "tokenize") return null;
  if (step.stage === "embed") {
    return {
      values: scene.pass.embedding,
      scale: scene.embedScale,
      label: "e",
      description: "the embedded input, token row plus position row",
    };
  }
  if (step.stage === "attend") {
    const lt = scene.pass.loops[step.loop - 1];
    return {
      values: lt.input,
      scale: scene.hiddenScale,
      label: step.loop === 1 ? "e" : `h${SUP[step.loop - 1]} + e`,
      description:
        step.loop === 1
          ? "what goes into the block on the first pass: h is still zero, so this is just e"
          : "what goes into the block on this pass: last pass's state with e added back",
    };
  }
  const loop = Math.min(step.loop, scene.loops);
  return {
    values: scene.pass.loops[loop - 1].hidden,
    scale: scene.hiddenScale,
    label: `h${SUP[loop]}`,
    description: `the state after ${loop} loop${loop === 1 ? "" : "s"}`,
  };
}
